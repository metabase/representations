/**
 * The texts the lint reads differently from Metabase, each a known
 * difference that `docs/lint.md` names: an offset followed by a zone that is
 * itself an offset of whole hours, which Metabase refuses; and an offset
 * written `+HHmm` before a zone in brackets, which Metabase refuses.
 */
const KNOWN_DIFFERENCES = new Set<string>([
  "2024-01-05T10:00:00+01:00[UTC+01]",
  "2024-01-05T10:00:00Z[UTC+01]",
  "2024-01-05T10:00:00+01:00[GMT-05]",
  "2024-01-05T10:00:00Z[GMT-05]",
  "2024-01-05T10:00:00+01:00[+01]",
  "2024-01-05T10:00:00Z[+01]",
  "2024-01-05T10:00:00+01:00[GMT+00]",
  "2024-01-05T10:00:00Z[GMT+00]",
  "2024-01-05T10:00:00+0130[Europe/Paris]",
]);

describe("the zone of a timestamp", () => {
  let workdir: string;

  beforeEach(() => {
    workdir = mkdtempSync(join(tmpdir(), "representations-zones-"));
    mkdirSync(join(workdir, "collections"));
  });

  afterEach(() => {
    rmSync(workdir, { recursive: true, force: true });
  });

  it("is read as Metabase reads it", () => {
    METABASE_READS.forEach(([text], i) =>
      writeFileSync(
        join(workdir, "collections", `t${String(i).padStart(4, "0")}.yaml`),
        `name: n\ncreated_at: ${JSON.stringify(text)}\n`,
      ),
    );
    const failed = new Set(
      validateSchema({ folder: workdir })
        .results.filter((r) => r.status === "fail")
        .map((r) => Number(/t(\d+)\.yaml$/.exec(r.file)?.[1])),
    );
    const differences = METABASE_READS.flatMap(([text, reads], i) =>
      reads === !failed.has(i) ? [] : [text],
    );
    expect(differences).toEqual(
      METABASE_READS.map(([text]) => text).filter((t) =>
        KNOWN_DIFFERENCES.has(t),
      ),
    );
  });
});
